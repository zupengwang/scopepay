import { createServer } from 'node:http';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { createApp } from './app.mjs';
import { createStore } from './store.mjs';
import { aiConfig, createAI } from './ai.mjs';
import { createPayPal } from './paypal.mjs';
if (existsSync('.env')) process.loadEnvFile('.env');
const env = process.env, host = env.HOST || '127.0.0.1', port = Number(env.PORT || 4181);
const origin = (env.APP_ORIGIN || `http://127.0.0.1:${port}`).replace(/\/$/, '');
const loopback = ['localhost', '127.0.0.1', '[::1]'].includes(new URL(origin).hostname);
if ((!['127.0.0.1', 'localhost', '::1'].includes(host) || !loopback) && (!env.ADMIN_PASSWORD || env.ADMIN_PASSWORD.length < 12)) throw new Error('Set ADMIN_PASSWORD (at least 12 characters) before exposing the workspace.');
if (!loopback && new URL(origin).protocol !== 'https:') throw new Error('Public deployments require an HTTPS APP_ORIGIN.');
const store = createStore(resolve(env.DATA_PATH || './data/scopepay.sqlite'));
const ai = createAI(aiConfig(env));
const paypal = createPayPal({ clientId: env.PAYPAL_CLIENT_ID, secret: env.PAYPAL_CLIENT_SECRET, origin });
const server = createServer(createApp({ store, ai, paypal, origin, adminPassword: env.ADMIN_PASSWORD, sessionSecret: env.ADMIN_SESSION_SECRET || undefined }));
server.requestTimeout = 90000; server.headersTimeout = 15000;
server.listen(port, host, () => console.log(`ScopePay: ${origin} | Model: ${ai.ready ? 'configured' : 'not configured'} | PayPal sandbox: ${paypal.ready ? 'configured' : 'not configured'}`));
for (const sig of ['SIGINT', 'SIGTERM']) process.once(sig, () => server.close(() => { store.close(); process.exit(0); }));
